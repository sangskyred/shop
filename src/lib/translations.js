export const translate = (value, language) => {
	const normalizedValue = nfc(value);
	if (language !== 'vi') {
		return normalizedValue;
	}
	if (vi[normalizedValue]) {
		return nfc(vi[normalizedValue]);
	}

	const searchTitle = normalizedValue.match(/^Results for “(.+)”$/);
	if (searchTitle) {
		return nfc(`${vi['Results for']} “${searchTitle[1]}”`);
	}

	const categoryTitle = normalizedValue.match(/^(.+) products$/);
	if (categoryTitle && vi[categoryTitle[1]]) {
		return nfc(`Sản phẩm ${vi[categoryTitle[1]]}`);
	}

	const collectionDescription = normalizedValue.match(/^Browse products in the (.+) collection\.$/);
	if (collectionDescription && vi[collectionDescription[1]]) {
		return nfc(`Khám phá sản phẩm trong bộ sưu tập ${vi[collectionDescription[1]]}.`);
	}

	return normalizedValue;
};
